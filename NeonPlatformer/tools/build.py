"""Builds the game. Run after changing levels, sounds or code:

    python tools/build.py

  1. levels/campaign.js        - campaign bundled for playing straight from disk
  2. sw.js                     - offline file list + new cache version
  3. build/NeonPlatformer.html - the whole game in ONE file (share/email/double-click)
  4. build/NeonPlatformer-web.zip - the folder version, ready for GitHub Pages / itch.io"""
import base64, hashlib, json, os, re, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)
OUT = P('build')
SHIP = ['index.html', 'manifest.webmanifest', 'sw.js', 'css', 'js', 'levels', 'audio', 'textures']

def rel_files():
    out = []
    for top in SHIP:
        p = P(top)
        if os.path.isfile(p):
            out.append(top)
        elif os.path.isdir(p):
            for d, _, fs in os.walk(p):
                for f in sorted(fs):
                    if f.lower().endswith('.md'):
                        continue
                    out.append(os.path.relpath(os.path.join(d, f), ROOT).replace(os.sep, '/'))
    return sorted(out)

# 1 ─ levels
camp = json.load(open(P('levels', 'campaign.json'), encoding='utf-8'))
levels = []
for fname in camp.get('levels', []):
    d = json.load(open(P('levels', fname), encoding='utf-8'))
    levels.append(d.get('data', d))
bundle = {'name': camp.get('name', ''), 'levels': levels}
open(P('levels', 'campaign.js'), 'w', encoding='utf-8').write(
    '// GENERATED by tools/build.py from levels/campaign.json - edit those files, not this one.\n'
    'window.NEON_CAMPAIGN=' + json.dumps(bundle, separators=(',', ':')) + ';\n')
print(f'levels      {len(levels)} in campaign')

# 2 ─ service worker
files = [f for f in rel_files() if f != 'sw.js']
h = hashlib.sha1(b''.join(open(P(f), 'rb').read() for f in files)).hexdigest()[:10]
sw = open(P('sw.js'), encoding='utf-8').read()
sw = re.sub(r"const VERSION = '[^']*';", f"const VERSION = 'neon-{h}';", sw)
sw = re.sub(r"const FILES = \[[^\]]*\];", 'const FILES = ' + json.dumps(['./'] + files) + ';', sw)
open(P('sw.js'), 'w', encoding='utf-8').write(sw)
print(f'offline     {len(files)} files cached (version neon-{h})')

# 3 ─ single file
html = open(P('index.html'), encoding='utf-8').read()
css = open(P('css', 'game.css'), encoding='utf-8').read()
html = html.replace('<link rel="stylesheet" href="css/game.css">', '<style>\n' + css + '</style>')
def inline(m):
    src = m.group(1)
    code = open(P(src), encoding='utf-8').read().replace('</script', '<\\/script')
    return f'<script>/* {src} */\n{code}</script>'
html = re.sub(r'<script src="([^"]+)"></script>', inline, html)
audio = {}
for kind in ('sfx', 'music'):
    d = P('audio', kind)
    for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if f.endswith('.wav'):
            audio[f'{kind}/{f[:-4]}'] = 'data:audio/wav;base64,' + base64.b64encode(open(os.path.join(d, f), 'rb').read()).decode()
html = html.replace('<!-- Levels:', '<script>window.NEON_SINGLE_FILE=true;window.NEON_AUDIO=' + json.dumps(audio) + ';</script>\n<!-- Levels:', 1)
icon = 'data:image/png;base64,' + base64.b64encode(open(P('textures', 'icons', 'icon-192.png'), 'rb').read()).decode()
html = html.replace('<link rel="manifest" href="manifest.webmanifest">\n', '')
html = html.replace('href="textures/icons/icon-192.png"', f'href="{icon}"')
os.makedirs(OUT, exist_ok=True)
open(os.path.join(OUT, 'NeonPlatformer.html'), 'w', encoding='utf-8').write(html)
print(f'single file build/NeonPlatformer.html ({len(html)//1024} KB)')

# 4 ─ web zip
zp = os.path.join(OUT, 'NeonPlatformer-web.zip')
with zipfile.ZipFile(zp, 'w', zipfile.ZIP_DEFLATED) as z:
    for f in ['sw.js'] + files:
        z.write(P(f), f)
print(f'web zip     build/NeonPlatformer-web.zip ({os.path.getsize(zp)//1024} KB)')
